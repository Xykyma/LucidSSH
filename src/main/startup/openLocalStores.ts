import { loadConfig } from '../config/store';
import { openHostsDb } from '../hosts/db';

/**
 * Открывает локальные хранилища при старте main — hosts.db строго до config.json.
 *
 * Порядок — условие сохранности данных при обновлении с 1.0.1 (UPD-04), а не
 * косметика. Миграция v3 hosts.db переносит `dashboard.dismissedAlerts` из
 * сырого config.json (ADR-0015), а `loadConfig()` это поле уже не знает:
 * первая же запись конфига — например, состояние развёрнутого окна через
 * 400 мс после старта — перепишет файл без него. Пока база открывалась лениво,
 * по первому запросу хостов из renderer, мьюты молча терялись всякий раз,
 * когда окно успевало сохраниться раньше.
 *
 * Ошибка открытия базы запуск не роняет: база остаётся закрытой, первое
 * обращение из IPC повторит `openHostsDb()` и вернёт ошибку туда же, куда и
 * при ленивом открытии.
 */
export function openLocalStores(): void {
  try {
    openHostsDb();
  } catch {
    // см. выше: повтор и доставка ошибки — на первом обращении из IPC
  }
  loadConfig();
}
